export const EXERCISES = STAGES.flatMap((stage) => stage.exercises.map((ex) => ({ ...ex, stage: stage.id })));

export function findExercise(id) {
  return EXERCISES.find((ex) => ex.id === id) ?? null;
}

/** Previous and next exercise in the recommended order. */
export function neighbours(id) {
  const i = EXERCISES.findIndex((ex) => ex.id === id);
  return { prev: EXERCISES[i - 1] ?? null, next: EXERCISES[i + 1] ?? null };
}

